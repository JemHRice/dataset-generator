def connect_postgres(create_db=True):
    """Connect to PostgreSQL and optionally create the database."""
    try:
        # First, connect to default 'postgres' database
        conn = psycopg2.connect(
            host=DB_HOST,
            port=DB_PORT,
            database="postgres",
            user=DB_USER,
            password=DB_PASSWORD,
        )
        conn.autocommit = True
        cur = conn.cursor()

        if create_db:
            try:
                cur.execute("""
                    SELECT pg_terminate_backend(pid)
                    FROM pg_stat_activity
                    WHERE datname = %s AND pid <> pg_backend_pid();
                """, (DB_NAME,))
                cur.execute(f"DROP DATABASE IF EXISTS {DB_NAME};")
                print(f"✓ Dropped existing database '{DB_NAME}'")
            except Exception as e:
                print(f"⚠ Could not drop database: {e}")

            try:
                cur.execute(f"CREATE DATABASE {DB_NAME};")
                print(f"✓ Created database '{DB_NAME}'")
            except Exception as e:
                print(f"✗ Error creating database: {e}")
                sys.exit(1)

        cur.close()
        conn.close()

        # Now connect to the actual sports_retail database
        conn = psycopg2.connect(
            host=DB_HOST,
            port=DB_PORT,
            database=DB_NAME,
            user=DB_USER,
            password=DB_PASSWORD,
        )
        return conn
    except Exception as e:
        print(f"✗ Database connection failed: {e}")
        print("Please ensure:")
        print(f"  - PostgreSQL is running on {DB_HOST}:{DB_PORT}")
        print(f"  - User '{DB_USER}' exists")
        print(f"  - .env file contains correct credentials")
        sys.exit(1)


def create_schema(conn):
    """Create all tables in the database."""
    cur = conn.cursor()

    print("\n[SCHEMA] Creating tables...")

    # dim_state
    cur.execute("""
        CREATE TABLE dim_state (
            state_id SERIAL PRIMARY KEY,
            state_name VARCHAR(50) NOT NULL,
            state_code VARCHAR(3) NOT NULL UNIQUE,
            population_weight FLOAT NOT NULL
        );
    """)

    # dim_store
    cur.execute("""
        CREATE TABLE dim_store (
            store_id SERIAL PRIMARY KEY,
            store_name VARCHAR(100) NOT NULL,
            suburb VARCHAR(100) NOT NULL,
            state_id INTEGER NOT NULL REFERENCES dim_state(state_id),
            postcode VARCHAR(5) NOT NULL,
            opening_date DATE NOT NULL
        );
    """)

    # dim_salesperson
    cur.execute("""
        CREATE TABLE dim_salesperson (
            salesperson_id SERIAL PRIMARY KEY,
            first_name VARCHAR(100) NOT NULL,
            last_name VARCHAR(100) NOT NULL,
            email VARCHAR(100) UNIQUE NOT NULL,
            hire_date DATE NOT NULL,
            store_id INTEGER NOT NULL REFERENCES dim_store(store_id)
        );
    """)

    # dim_product
    cur.execute("""
        CREATE TABLE dim_product (
            product_id SERIAL PRIMARY KEY,
            product_name VARCHAR(200) NOT NULL,
            brand VARCHAR(100) NOT NULL,
            category VARCHAR(50) NOT NULL,
            subcategory VARCHAR(100) NOT NULL,
            unit_cost NUMERIC(10, 2) NOT NULL,
            unit_price NUMERIC(10, 2) NOT NULL,
            weight_kg NUMERIC(8, 3) NOT NULL
        );
    """)

    # dim_shipping_method
    cur.execute("""
        CREATE TABLE dim_shipping_method (
            shipping_method_id SERIAL PRIMARY KEY,
            method_name VARCHAR(100) NOT NULL,
            carrier VARCHAR(100) NOT NULL,
            estimated_days_min INTEGER NOT NULL,
            estimated_days_max INTEGER NOT NULL,
            flat_cost NUMERIC(10, 2) NOT NULL
        );
    """)

    # dim_promotions
    cur.execute("""
        CREATE TABLE dim_promotions (
            promotion_id SERIAL PRIMARY KEY,
            promotion_name VARCHAR(200) NOT NULL,
            start_date DATE NOT NULL,
            end_date DATE NOT NULL,
            discount_rate FLOAT NOT NULL,
            affected_category VARCHAR(50) NOT NULL
        );
    """)

    # dim_date
    cur.execute("""
        CREATE TABLE dim_date (
            date_id SERIAL PRIMARY KEY,
            full_date DATE NOT NULL UNIQUE,
            day INTEGER NOT NULL,
            month INTEGER NOT NULL,
            month_name VARCHAR(20) NOT NULL,
            quarter INTEGER NOT NULL,
            year INTEGER NOT NULL,
            week_of_year INTEGER NOT NULL,
            day_of_week INTEGER NOT NULL,
            day_name VARCHAR(20) NOT NULL,
            is_weekend BOOLEAN NOT NULL,
            is_public_holiday BOOLEAN NOT NULL,
            financial_year VARCHAR(9) NOT NULL,
            season VARCHAR(20) NOT NULL
        );
    """)

    # fact_orders
    cur.execute("""
        CREATE TABLE fact_orders (
            order_id SERIAL PRIMARY KEY,
            order_date_id INTEGER NOT NULL REFERENCES dim_date(date_id),
            store_id INTEGER NOT NULL REFERENCES dim_store(store_id),
            salesperson_id INTEGER NOT NULL REFERENCES dim_salesperson(salesperson_id),
            shipping_method_id INTEGER NOT NULL REFERENCES dim_shipping_method(shipping_method_id),
            customer_id INTEGER NOT NULL,
            order_status VARCHAR(20) NOT NULL,
            shipping_cost NUMERIC(10, 2) NOT NULL,
            total_order_value NUMERIC(12, 2) NOT NULL
        );
    """)

    # fact_order_items
    cur.execute("""
        CREATE TABLE fact_order_items (
            order_item_id SERIAL PRIMARY KEY,
            order_id INTEGER NOT NULL REFERENCES fact_orders(order_id),
            product_id INTEGER NOT NULL REFERENCES dim_product(product_id),
            quantity INTEGER NOT NULL CHECK (quantity >= 1 AND quantity <= 5),
            unit_price_at_sale NUMERIC(10, 2) NOT NULL,
            discount_applied NUMERIC(5, 3) NOT NULL CHECK (discount_applied >= 0 AND discount_applied <= 1),
            line_total NUMERIC(12, 2) NOT NULL
        );
    """)

    conn.commit()
    print("✓ Schema created successfully")


