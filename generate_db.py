def generate_fact_orders(conn):
    """Generate order fact table with temporal distribution and seasonality."""
    print("\n[ORDERS] Generating order data...")

    cur = conn.cursor()

    # Get necessary data
    cur.execute("SELECT store_id FROM dim_store;")
    store_ids = np.array([row[0] for row in cur.fetchall()])

    cur.execute("SELECT salesperson_id, store_id FROM dim_salesperson;")
    salesperson_rows = cur.fetchall()
    salesperson_by_store = {}
    for sp_id, store_id in salesperson_rows:
        if store_id not in salesperson_by_store:
            salesperson_by_store[store_id] = []
        salesperson_by_store[store_id].append(sp_id)

    cur.execute("SELECT date_id, full_date, season FROM dim_date ORDER BY full_date;")
    date_rows = cur.fetchall()
    date_map = {row[1]: row[0] for row in date_rows}

    cur.execute(
        "SELECT shipping_method_id, flat_cost, estimated_days_min, estimated_days_max FROM dim_shipping_method;"
    )
    shipping_rows = cur.fetchall()
    shipping_methods = [row[0] for row in shipping_rows]
    shipping_cost_lookup = {row[0]: float(row[1]) for row in shipping_rows}
    shipping_days_lookup = {row[0]: (int(row[2]), int(row[3])) for row in shipping_rows}

    cur.execute(
        "SELECT promotion_id, start_date, end_date, affected_category, discount_rate FROM dim_promotions;"
    )
    promotions = cur.fetchall()

    cur.execute("SELECT product_id, category FROM dim_product;")
    product_rows = cur.fetchall()
    products_by_category = {}
    for prod_id, cat in product_rows:
        if cat not in products_by_category:
            products_by_category[cat] = []
        products_by_category[cat].append(prod_id)

    # Load customers sorted by signup date, with a hidden purchase-frequency
    # weight per customer (lognormal: most buy rarely, a few buy a lot). Sorting
    # by signup date lets us sample only customers who already exist on each day.
    cur.execute("SELECT customer_id, signup_date FROM dim_customer ORDER BY signup_date;")
    customer_rows = cur.fetchall()
    customer_ids = np.array([row[0] for row in customer_rows])
    customer_signups = [row[1] for row in customer_rows]
    customer_weights = np.random.lognormal(
        mean=0.0, sigma=CUSTOMER_REPEAT_SIGMA, size=len(customer_ids)
    )

    # Assign weights to stores
    store_weights = {store_id: np.random.uniform(0.5, 3.0) for store_id in store_ids}

    # Assign weights to salespeople
    salesperson_weights = {}
    for sp_id, _ in salesperson_rows:
        salesperson_weights[sp_id] = np.random.uniform(0.5, 2.5)

    # Generate orders with temporal distribution
    orders = []
    order_date_volumes = {}
    daily_promo_boosts = {}

    # Calculate base daily volume and apply yearly trends
    days_in_period = (GENERATION_END_DATE - GENERATION_START_DATE).days + 1
    base_daily_volume = TARGET_ORDERS / days_in_period

    # Apply yearly trends: ±5% to ±15% change per year
    _y2020 = 1.0
    _y2021 = _y2020 + np.random.uniform(-0.05, 0.15)
    _y2022 = _y2021 + np.random.uniform(-0.05, 0.15)
    _y2023 = _y2022 + np.random.uniform(-0.05, 0.15)
    _y2024 = _y2023 + np.random.uniform(-0.05, 0.15)
    yearly_multipliers = {
        2020: _y2020,
        2021: _y2021,
        2022: _y2022,
        2023: _y2023,
        2024: _y2024,
    }

    # Apply promotional boosts
    for prom_id, start, end, category, discount_rate in promotions:
        current = start
        while current <= end:
            daily_promo_boosts[current] = np.random.uniform(0.20, 0.60)
            current += timedelta(days=1)

    # Generate order dates with distribution
    for date_id, full_date, season in date_rows:
        year = full_date.year
        month = full_date.month
        yearly_mult = yearly_multipliers.get(year, 1.0)

        # Month seasonality weights
        month_weights = {
            1: 1.3,  # Jan - New Year
            2: 0.9,
            3: 1.0,  # Autumn
            4: 0.95,
            5: 1.05,
            6: 1.1,  # Winter/FY turnover
            7: 1.15,  # New FY, school holidays
            8: 1.0,
            9: 1.1,  # Spring
            10: 1.2,  # Spring peak
            11: 1.15,
            12: 1.4,  # Christmas peak
        }
        month_mult = month_weights.get(month, 1.0)

        # Promotions boost
        promo_boost = daily_promo_boosts.get(full_date, 0.0)

        # Add jitter (±15%)
        jitter = np.random.uniform(0.85, 1.15)

        daily_volume = int(
            base_daily_volume * yearly_mult * month_mult * (1 + promo_boost) * jitter
        )
        order_date_volumes[date_id] = daily_volume

    # Precompute normalized store weight array for efficient sampling
    store_weight_array = np.array([store_weights[sid] for sid in store_ids])
    store_weight_array = store_weight_array / store_weight_array.sum()

    # Reverse date lookup (date_id -> full_date) for fulfillment-date arithmetic
    id_to_date = {row[0]: row[1] for row in date_rows}

    # Generate orders. Days are processed chronologically (order_date_volumes is
    # built in date order), so we can grow the eligible-customer prefix as we go.
    elig_count = 0  # customers who have signed up on/before the current day
    for date_id, volume in order_date_volumes.items():
        full_date = id_to_date[date_id]

        # Advance customer eligibility to include everyone signed up by today
        while elig_count < len(customer_signups) and customer_signups[elig_count] <= full_date:
            elig_count += 1

        # Sample this day's customers (weighted by purchase frequency)
        if elig_count > 0 and volume > 0:
            elig_weights = customer_weights[:elig_count]
            elig_weights = elig_weights / elig_weights.sum()
            day_customers = np.random.choice(
                customer_ids[:elig_count], size=volume, p=elig_weights
            )
        else:
            day_customers = np.array([], dtype=int)

        for i in range(volume):
            store_id = int(np.random.choice(store_ids, p=store_weight_array))
            available_salespersons = salesperson_by_store.get(store_id, [])
            if not available_salespersons:
                continue

            sp_weights = np.array(
                [salesperson_weights[sp] for sp in available_salespersons]
            )
            sp_weights = sp_weights / sp_weights.sum()
            salesperson_id = int(np.random.choice(available_salespersons, p=sp_weights))

            shipping_method_id = int(np.random.choice(shipping_methods))
            customer_id = int(day_customers[i])

            # Order status: 94% delivered, 3% processing, 3% cancelled
            status = np.random.choice(
                ["Delivered", "Processing", "Cancelled"], p=[0.94, 0.03, 0.03]
            )

            shipping_cost = shipping_cost_lookup[shipping_method_id]

            # Fulfillment dates: only Delivered orders have ship + delivery dates.
            # Processing (not yet shipped) and Cancelled have neither. Dates that
            # fall past the end of dim_date are left NULL (still in transit).
            ship_date_id = None
            delivery_date_id = None
            if status == "Delivered":
                lag = int(np.random.randint(0, 3))  # 0-2 day processing lag
                ship_date = full_date + timedelta(days=lag)
                ship_date_id = date_map.get(ship_date)
                dmin, dmax = shipping_days_lookup[shipping_method_id]
                transit = int(np.random.randint(dmin, dmax + 1))
                delivery_date = ship_date + timedelta(days=transit)
                delivery_date_id = date_map.get(delivery_date)

            # Placeholder for total_order_value (will be calculated from line items)
            total_order_value = 0.0

            orders.append(
                (
                    date_id,
                    ship_date_id,
                    delivery_date_id,
                    store_id,
                    salesperson_id,
                    shipping_method_id,
                    customer_id,
                    status,
                    float(shipping_cost),
                    total_order_value,
                )
            )

    # Batch insert orders
    print(f"  Inserting {len(orders):,} orders...")
    execute_batch(
        cur,
        """
        INSERT INTO fact_orders
        (order_date_id, ship_date_id, delivery_date_id, store_id, salesperson_id, shipping_method_id, customer_id, order_status, shipping_cost, total_order_value)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
        """,
        orders,
        page_size=1000,
    )
    conn.commit()
    print(f"✓ {len(orders):,} orders inserted")

    return orders, products_by_category, date_map, promotions


def generate_fact_order_items(conn, orders, products_by_category, date_map, promotions):
    """Generate order items with realistic distribution and promotions."""
    print("\n[ORDER ITEMS] Generating line items...")

    cur = conn.cursor()

    # Get product data
    cur.execute("""
        SELECT product_id, unit_price, category FROM dim_product
        ORDER BY product_id;
    """)
    product_rows = cur.fetchall()
    product_data = {
        row[0]: {"price": row[1], "category": row[2]} for row in product_rows
    }

    # Assign popularity weights
    product_weights = {pid: np.random.uniform(0.1, 3.0) for pid in product_data.keys()}

    # Get promotion dates for mapping
    promo_date_map = {}
    for prom_id, start, end, category, discount_rate in promotions:
        current = start
        while current <= end:
            if current not in promo_date_map:
                promo_date_map[current] = []
            promo_date_map[current].append((prom_id, category, float(discount_rate)))
            current += timedelta(days=1)

    # Get order dates for reference
    cur.execute("SELECT order_id, order_date_id FROM fact_orders ORDER BY order_id;")
    order_dates = {row[0]: row[1] for row in cur.fetchall()}

    cur.execute("SELECT date_id, full_date FROM dim_date;")
    date_lookup = {row[0]: row[1] for row in cur.fetchall()}

    line_items = []

    for order_id, (
        date_id,
        ship_date_id,
        delivery_date_id,
        store_id,
        sp_id,
        shipping_id,
        cust_id,
        status,
        ship_cost,
        _,
    ) in enumerate(orders, 1):
        # Determine number of items in order (1-5, avg ~4)
        num_items = np.random.choice([1, 2, 3, 4, 5], p=[0.05, 0.15, 0.3, 0.35, 0.15])

        order_full_date = date_lookup.get(date_id)
        active_promos = promo_date_map.get(order_full_date, [])

        for _ in range(num_items):
            # Select product based on popularity weights
            product_ids = list(product_weights.keys())
            weights = np.array([product_weights[pid] for pid in product_ids])
            weights = weights / weights.sum()

            # Boost weights for products in active promotions
            for prom_id, promo_category, _ in active_promos:
                for i, pid in enumerate(product_ids):
                    if product_data[pid]["category"] == promo_category:
                        weights[i] *= 1.5

            weights = weights / weights.sum()
            product_id = int(np.random.choice(product_ids, p=weights))

            quantity = int(np.random.randint(1, 6))
            unit_price = float(product_data[product_id]["price"])
            product_category = product_data[product_id]["category"]

            # Determine discount. A promotion only applies to items in its own
            # category; the matching promotion is recorded against the line so
            # promo lift can be attributed directly.
            matching_promo = next(
                (p for p in active_promos if p[1] == product_category), None
            )
            if matching_promo is not None:
                promotion_id = matching_promo[0]
                base_discount = matching_promo[2]  # discount_rate
                discount = min(
                    0.3, max(0.0, base_discount + np.random.uniform(-0.05, 0.05))
                )
            else:
                # No promotion for this category
                promotion_id = None
                discount_rand = np.random.random()
                if discount_rand < 0.70:
                    discount = 0.0
                elif discount_rand < 0.90:
                    discount = np.random.uniform(0.05, 0.15)
                else:
                    discount = np.random.uniform(0.15, 0.25)

            line_total = quantity * unit_price * (1.0 - discount)

            line_items.append(
                (
                    order_id,
                    product_id,
                    quantity,
                    unit_price,
                    discount,
                    line_total,
                    promotion_id,
                )
            )

    print(f"  Inserting {len(line_items):,} line items...")
    execute_batch(
        cur,
        """
        INSERT INTO fact_order_items
        (order_id, product_id, quantity, unit_price_at_sale, discount_applied, line_total, promotion_id)
        VALUES (%s, %s, %s, %s, %s, %s, %s)
        """,
        line_items,
        page_size=1000,
    )
    conn.commit()

    # Roll the line items up into the order header in one set-based statement.
    # Doing this as one UPDATE per order meant ~400k round-trips and was by far
    # the slowest step in the run.
    # total_order_value is what the customer actually paid: the sum of the
    # discounted line totals plus the shipping charge on the header. Leaving
    # shipping out meant the header never reconciled to a real invoice.
    print("  Updating order totals...")
    cur.execute("""
        UPDATE fact_orders o
        SET total_order_value = li.line_sum + o.shipping_cost
        FROM (
            SELECT order_id, SUM(line_total) AS line_sum
            FROM fact_order_items
            GROUP BY order_id
        ) li
        WHERE o.order_id = li.order_id;
    """)
    conn.commit()

    print(f"✓ {len(line_items):,} line items inserted")


