def generate_dim_date():
    """Generate date dimension covering 2020-2024."""
    data = []
    current = GENERATION_START_DATE

    days_of_week = [
        "Monday",
        "Tuesday",
        "Wednesday",
        "Thursday",
        "Friday",
        "Saturday",
        "Sunday",
    ]
    month_names = [
        "January",
        "February",
        "March",
        "April",
        "May",
        "June",
        "July",
        "August",
        "September",
        "October",
        "November",
        "December",
    ]

    while current <= GENERATION_END_DATE:
        day = current.day
        month = current.month
        month_name = month_names[month - 1]
        quarter = (month - 1) // 3 + 1
        year = current.year
        week_of_year = current.isocalendar()[1]
        day_of_week = current.weekday() + 1
        day_name = days_of_week[current.weekday()]
        is_weekend = day_of_week >= 6

        # AU Financial Year: July-June
        if month >= 7:
            financial_year = f"{year}/{year+1}"
        else:
            financial_year = f"{year-1}/{year}"

        # AU Seasons: Summer=Dec-Feb, Autumn=Mar-May, Winter=Jun-Aug, Spring=Sep-Nov
        if month in [12, 1, 2]:
            season = "Summer"
        elif month in [3, 4, 5]:
            season = "Autumn"
        elif month in [6, 7, 8]:
            season = "Winter"
        else:
            season = "Spring"

        is_public_holiday = current in PUBLIC_HOLIDAYS

        data.append(
            (
                current,
                day,
                month,
                month_name,
                quarter,
                year,
                week_of_year,
                day_of_week,
                day_name,
                is_weekend,
                is_public_holiday,
                financial_year,
                season,
            )
        )

        current += timedelta(days=1)

    return data


